"""Turn the 18 Oct 2026 WooCommerce Store API snapshot into v5 seed data.

Reads ../ecocart-site/new-site/{products,cats}.json (read only) and writes:
  supabase/seed.sql      rows for categories, products and draft product_eco
  src/data/catalog.json  the same catalogue, bundled so the first paint has real content

The live sync (supabase/functions/sync-catalog) applies the same cleaning rules.
Usage: python3 scripts/seed.py
"""
import html
import json
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "ecocart-site" / "new-site"

# Copy that contradicts the store facts (flat ₹55 shipping, no COD) is dropped.
FALSE_COPY = re.compile(r"free (shipping|delivery)|complimentary shipping|cash on delivery|\bcod\b", re.I)


def clean(s: str) -> str:
    return re.sub(r"\s+", " ", unicodedata.normalize("NFKC", html.unescape(s or ""))).strip()


def paragraphs(h: str) -> list[str]:
    h = re.sub(r"(?i)<br\s*/?>|</(p|h[1-6]|li|div)>", "\n", h or "")
    out = []
    for line in re.sub(r"<[^>]+>", " ", h).split("\n"):
        t = clean(line)
        if len(t) > 1 and not FALSE_COPY.search(t):
            out.append(t)
    return out


def paise(v):
    return int(v) if v not in (None, "") else None


VARIATION_PRICES = {int(k): v for k, v in json.load(open(ROOT / "scripts" / "variation-prices.json")).items() if k[0] != "_"}


def product(p, order):
    pr = p["prices"]
    rng = pr.get("price_range")
    attrs = [{"name": clean(a["name"]), "terms": [clean(t["name"]) for t in a.get("terms", [])]}
             for a in p.get("attributes", []) if a.get("has_variations")]
    variations = [{"id": v["id"],
                   "attrs": {clean(a["name"]): clean(a["value"]) for a in v["attributes"]},
                   "price": (VARIATION_PRICES.get(v["id"]) if rng else paise(pr["price"])) or None}
                  for v in p.get("variations", [])]
    summary = " ".join(paragraphs(p["short_description"]))[:400]
    desc = paragraphs(p["description"])
    return {
        "id": p["id"], "slug": p["slug"], "name": clean(p["name"]), "type": p["type"],
        "summary": summary or (desc[0][:400] if desc else ""),
        "description": "\n\n".join(desc),
        "price": paise(rng["min_amount"] if rng else pr["price"]),
        "regular_price": paise(pr["regular_price"]),
        "price_max": paise(rng["max_amount"]) if rng and rng["max_amount"] != rng["min_amount"] else None,
        "on_sale": bool(p["on_sale"]), "in_stock": bool(p["is_in_stock"]),
        "images": [{"src": i["src"], "thumb": i.get("thumbnail") or i["src"], "alt": clean(i.get("alt") or p["name"])}
                   for i in p["images"]],
        "category_ids": [c["id"] for c in p["categories"]],
        "attributes": attrs, "variations": variations,
        "permalink": p["permalink"], "menu_order": order,
    }


def draft_eco(p, cats):
    """Only facts that follow from what the product is. Saved unverified; never shown until an admin verifies."""
    names = {cats[c]["slug"] for c in p["category_ids"] if c in cats}
    n = p["name"].lower()
    e = {}
    if "coconut-shell-products" in names or "coconut shell" in n:
        e = {"material": "Coconut shell", "plant_based": True, "biodegradable": True}
    elif "bamboo-tissue" in names:
        e = {"material": "Bamboo", "plant_based": True}
    elif "homemade-soaps" in names:
        e = {"material": "Soap", "handmade": True}
    if "handmade" in n or "homemade" in n:
        e["handmade"] = True
    return e or None


def sql(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, (list, dict)):
        return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def main():
    raw_cats = json.load(open(SRC / "cats.json"))
    raw_products = json.load(open(SRC / "products.json"))
    cats = [{"id": c["id"], "name": clean(c["name"]), "slug": c["slug"], "parent": c["parent"], "count": c["count"]}
            for c in raw_cats]
    by_id = {c["id"]: c for c in cats}
    products = [product(p, i) for i, p in enumerate(raw_products)]

    lines = ["-- Generated by scripts/seed.py from the 18 Oct 2026 snapshot. Safe to re-run.", "begin;"]
    for c in cats:
        lines.append(f"insert into public.categories (id, name, slug, parent, count) values ({c['id']}, {sql(c['name'])}, {sql(c['slug'])}, {c['parent']}, {c['count']}) "
                     "on conflict (id) do update set name = excluded.name, slug = excluded.slug, parent = excluded.parent, count = excluded.count, updated_at = now();")
    cols = ["id", "slug", "name", "type", "summary", "description", "price", "regular_price", "price_max", "on_sale",
            "in_stock", "images", "category_ids", "attributes", "variations", "permalink", "menu_order"]
    for p in products:
        vals = [sql(p[k]) if k != "category_ids" else "'{" + ",".join(map(str, p[k])) + "}'::integer[]" for k in cols]
        upd = ", ".join(f"{k} = excluded.{k}" for k in cols[1:])
        lines.append(f"insert into public.products ({', '.join(cols)}) values ({', '.join(vals)}) on conflict (id) do update set {upd}, synced_at = now();")
    for p in products:
        e = draft_eco(p, by_id)
        if e:
            ks = list(e)
            lines.append(f"insert into public.product_eco (product_id, {', '.join(ks)}) values ({p['id']}, {', '.join(sql(e[k]) for k in ks)}) on conflict (product_id) do nothing;")
    lines.append("commit;")
    (ROOT / "supabase" / "seed.sql").write_text("\n".join(lines) + "\n")

    # Bundled snapshot: everything a list or product screen needs on first paint.
    # Long descriptions are left out (about 270 KB); the product screen loads them from Supabase.
    lite = [{k: v for k, v in p.items() if k != "description"} for p in products]
    (ROOT / "src" / "data").mkdir(exist_ok=True)
    (ROOT / "src" / "data" / "catalog.json").write_text(json.dumps(
        {"snapshot": "2026-10-18", "categories": cats, "products": lite}, ensure_ascii=False, separators=(",", ":")))
    print(len(cats), "categories,", len(products), "products,",
          sum(1 for p in products if draft_eco(p, by_id)), "draft eco cards")


main()
